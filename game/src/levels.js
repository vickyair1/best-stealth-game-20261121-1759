/** Validate every level grid: 18 rows of 25 known characters, one P, one R, one E. */
export function validateLevels() {
  const known = new Set(['#', '.', ',', 'C', 'X', 'L', 'o', 'R', 'E', 'P', 'D']);
  const problems = [];
  LEVELS.forEach((level, li) => {
    if (level.grid.length !== 18) problems.push(`level ${li + 1}: ${level.grid.length} rows`);
    level.grid.forEach((row, ri) => {
      if (row.length !== 25) problems.push(`level ${li + 1} row ${ri}: ${row.length} chars`);
      for (const ch of row) if (!known.has(ch)) problems.push(`level ${li + 1} row ${ri}: bad char ${ch}`);
    });
    for (const key of ['P', 'R', 'E']) {
      const n = level.grid.join('').split(key).length - 1;
      if (n !== 1) problems.push(`level ${li + 1}: ${n} x '${key}'`);
    }
  });
  return problems;
}
